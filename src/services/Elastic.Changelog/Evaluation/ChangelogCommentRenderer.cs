using System.Text;

namespace Elastic.Changelog.Evaluation;

/// <summary>
/// Renders the three changelog PR comment bodies.
/// <para>
/// Ported from the predecessor JS scripts in <c>changelog/submit/apply/scripts/</c>:
/// <list type="bullet">
///   <item><c>post-success-comment.js</c> → <see cref="RenderEntryCommitted"/></item>
///   <item><c>post-comment-only.js</c>     → <see cref="RenderCommentOnly"/></item>
///   <item><c>post-failure-comment.js</c>  → <see cref="RenderCannotGenerate"/></item>
/// </list>
/// </para>
/// <para>
/// Injection hardening: <see cref="WrapCodeFence"/> computes the longest backtick run in the
/// content and opens with <c>max(3, run + 1)</c> backticks; <see cref="WrapInlineCode"/> pads when
/// a value starts or ends with a backtick.  All dynamic values are embedded via ordinary string
/// interpolation, never injected into a GitHub Actions expression.
/// </para>
/// </summary>
internal static class ChangelogCommentRenderer
{
	/// <summary>
	/// Title prefix shared with the legacy JS comment-helper. Must remain the first line of every
	/// body so <c>GitHubCommentService</c>'s legacy-prefix fallback keeps working during rollout.
	/// </summary>
	internal const string Title = "### 📋 Changelog";

	/// <summary>GitHub comment body character limit.</summary>
	private const int MaxBodyLength = 65536;

	// ──────────────────────────────────────────────────────────────────────────────────────────
	// Public render methods
	// ──────────────────────────────────────────────────────────────────────────────────────────

	/// <summary>
	/// Renders the "entry committed" body: blob and edit links for the committed changelog file.
	/// </summary>
	internal static string RenderEntryCommitted(string owner, string repo, string headRef, string committedFile)
	{
		var safeBranch = Uri.EscapeDataString(headRef);
		var safePath = string.Join("/", committedFile.Split('/').Select(Uri.EscapeDataString));
		var viewUrl = $"https://github.com/{owner}/{repo}/blob/{safeBranch}/{safePath}";
		var editUrl = $"https://github.com/{owner}/{repo}/edit/{safeBranch}/{safePath}";

		return Truncate(
			string.Join(
				"\n",
				Title,
				"",
				$"📝 Changelog entry committed: [{WrapInlineCode(committedFile)}]({viewUrl})",
				"",
				$"✏️ [Edit this changelog]({editUrl})"
			)
		);
	}

	/// <summary>
	/// Renders the "comment-only" body: the generated YAML in a fenced block, with one of three
	/// guidance variants based on the commit context.
	/// </summary>
	internal static string RenderCommentOnly(
		string? changelogDir,
		string? yamlContent,
		string? yamlFilename,
		bool isFork,
		bool commitFailed
	)
	{
		var parts = new List<string> { Title, "" };

		if (!string.IsNullOrWhiteSpace(yamlContent) && !string.IsNullOrWhiteSpace(yamlFilename))
		{
			var guidance = commitFailed
				? "The workflow could not commit this generated changelog change to the PR branch, "
					+ "so the merge-time S3 upload will not include it. Resolve the commit failure or add "
					+ "the generated entry to the PR branch before merging."
				: isFork
					? "This comment is informational — editing it does not change what gets uploaded. "
						+ "On merge, the entry is regenerated from the live PR record (title, labels) and uploaded to S3. "
						+ "To change the preview, edit the PR title or labels and let the changelog workflow re-run."
					: "This comment is informational — editing it does not change what gets uploaded. "
						+ "Comment-only mode did not commit this generated changelog change to the PR branch, "
						+ "and same-repository PRs are not regenerated by the merge-time S3 upload. "
						+ "Add the generated entry to the PR branch before merging if it should be published.";

			var targetPath = string.IsNullOrWhiteSpace(changelogDir) ? yamlFilename : changelogDir + "/" + yamlFilename;
			parts.Add($"Generated changelog entry for {WrapInlineCode(targetPath)}:");
			parts.Add("");
			parts.Add(WrapCodeFence(yamlContent.Trim(), "yaml"));
			parts.Add("");
			parts.Add(guidance);
		}
		else
		{
			parts.Add("⚠️ Changelog entry was generated but the file content could not be read.");
		}

		return Truncate(string.Join("\n", parts));
	}

	/// <summary>
	/// Renders the Step 1 (label gate) comment body: tells the author which labels are required
	/// before a changelog entry can be generated. Tone is "labels not set yet", not "generation
	/// failed" — the author just hasn't told us what type of change this is.
	/// <para>
	/// Step 2 (changelog file invalid) and Step 3 (full require-changelog-file failure) will use
	/// separate render methods added when those workflow paths are built.
	/// </para>
	/// </summary>
	internal static string RenderCannotGenerate(string? labelTable, string? productLabelTable, string? skipLabels, string? configFile)
	{
		var configFileCode = WrapInlineCode(string.IsNullOrWhiteSpace(configFile) ? "docs/changelog.yml" : configFile);

		var hasTypeIssue = !string.IsNullOrWhiteSpace(labelTable);
		var hasProductIssue = !string.IsNullOrWhiteSpace(productLabelTable);

		var headline = hasTypeIssue && hasProductIssue
			? "🏷️ **Changelog labels needed** — add type and product labels to this PR to enable changelog generation."
			: hasProductIssue
				? "🏷️ **Product label needed** — add a product label to this PR to enable changelog generation."
				: "🏷️ **Changelog label needed** — add a type label to this PR to enable changelog generation.";

		var sections = new List<string>();

		if (hasTypeIssue)
			sections.Add(string.Join("\n", "", "🔖 Add one of these **type** labels to your PR:", "", labelTable));
		else if (!hasProductIssue)
			sections.Add($"\nAdd a type label that matches your {WrapInlineCode("pivot.types")} configuration in {configFileCode}.");

		if (hasProductIssue)
			sections.Add(string.Join("\n", "", "📦 Add one or more **product** labels to your PR:", "", productLabelTable));

		string skipSection;
		if (!string.IsNullOrWhiteSpace(skipLabels))
		{
			var formatted = skipLabels.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries).Select(
				WrapInlineCode
			);
			skipSection = $"\n⏭️ To skip changelog generation, add one of these labels: {string.Join(", ", formatted)}";
		}
		else
		{
			skipSection = $"\n⏭️ No skip labels are configured. To allow skipping changelog generation, "
				+ $"add a label to {WrapInlineCode("rules.create.exclude")} in {configFileCode}.";
		}

		var allParts = new List<string> { Title, "", headline };
		allParts.AddRange(sections);
		allParts.Add(skipSection);
		allParts.Add("");
		allParts.Add($"📄 See {configFileCode} for the full changelog configuration.");

		return Truncate(string.Join("\n", allParts));
	}

	/// <summary>
	/// Renders the "resolved" body posted when a previously-failing PR now has the required labels,
	/// clearing the stale Step 1 comment and confirming what happens next.
	/// </summary>
	internal static string RenderResolved() =>
		string.Join("\n", Title, "", "✅ **Changelog label set** — an entry will be generated on merge.");

	// ──────────────────────────────────────────────────────────────────────────────────────────
	// Injection-hardening helpers (ported from comment-helper.js)
	// ──────────────────────────────────────────────────────────────────────────────────────────

	/// <summary>
	/// Wraps <paramref name="content"/> in a fenced code block, using enough backticks to ensure
	/// embedded fence markers cannot escape the block.
	/// </summary>
	internal static string WrapCodeFence(string content, string language = "")
	{
		var fence = new string('`', Math.Max(3, LongestBacktickRun(content) + 1));
		return $"{fence}{language}\n{content}\n{fence}";
	}

	/// <summary>
	/// Wraps <paramref name="value"/> as inline code, using enough backticks to accommodate embedded
	/// backticks, and padding when the value starts or ends with a backtick.
	/// </summary>
	internal static string WrapInlineCode(string value)
	{
		var delimiter = new string('`', LongestBacktickRun(value) + 1);
		var padded = value.StartsWith('`') || value.EndsWith('`') ? $" {value} " : value;
		return $"{delimiter}{padded}{delimiter}";
	}

	private static int LongestBacktickRun(string value)
	{
		var longest = 0;
		var current = 0;
		foreach (var ch in value)
		{
			if (ch == '`')
				current++;
			else
			{
				if (current > longest)
					longest = current;
				current = 0;
			}
		}
		return Math.Max(longest, current);
	}

	private static string Truncate(string body)
	{
		if (body.Length <= MaxBodyLength)
			return body;

		const string suffix = "\n\n…*(truncated — body exceeds GitHub's 65 536-character limit)*";
		return body[..(MaxBodyLength - suffix.Length)] + suffix;
	}
}
