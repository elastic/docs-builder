using System.Text;
using System.Text.RegularExpressions;

namespace Elastic.Documentation.Journeys.Cli.Synthetics;

/// <summary>What the export sends to <c>@nullean/journeys</c> and what <c>push</c> sends to <c>@elastic/synthetics</c>.</summary>
internal sealed record ExportContext(string? Env, string? BuildType, IReadOnlySet<string> Features);

/// <summary>
/// Builds the commands and the project config for the Synthetics monitors. Nothing here starts a process, so the
/// exact arguments can be checked without Node, a network or a Kibana.
/// </summary>
internal static partial class SyntheticsPlan
{
	/// <summary>The exporter; its bin is <c>journeys</c>. Pinned so a monitor push never changes with a release of its tool.</summary>
	public const string JourneysPackage = "@nullean/journeys@0.9.0";

	/// <summary>The same <c>@elastic/synthetics</c> version <c>@nullean/journeys</c> tests its generated files against.</summary>
	public const string SyntheticsPackage = "@elastic/synthetics@1.27.0";

	public const string DefaultKibanaUrl = "https://elastic-docs-v3-prod-e6053a.kb.us-east-1.aws.elastic.cloud/";
	public const string DefaultSpace = "default";
	public const string ApiKeyVariable = "SYNTHETICS_API_KEY";

	public static string DefaultProject(string env) => $"elastic-co-docs-{env}";

	public static string JourneysFolder(string outDir) => Path.Combine(outDir, "journeys");

	public static string ConfigPath(string outDir) => Path.Combine(outDir, "synthetics.config.ts");

	/// <summary>Only prod pages: Kibana routes an alert tagged <c>alert:pagerduty</c>, and edge and demo must never page.</summary>
	public static bool MayPage(string? env) => env == "prod";

	public static IReadOnlyList<string> ExportArguments(string journeys, string outDir, ExportContext context, bool paging, Uri baseUrl)
	{
		var arguments = new List<string>
		{
			"--yes",
			JourneysPackage,
			"export-synthetics",
			journeys,
			"--out",
			JourneysFolder(outDir),
			"--root",
			journeys,
			"--base-url",
			baseUrl.GetLeftPart(UriPartial.Authority)
		};
		if (context.Features.Count > 0)
			arguments.AddRange(["--features", string.Join(',', context.Features.Order(StringComparer.Ordinal))]);
		if (context.BuildType is not null)
			arguments.AddRange(["--build-type", context.BuildType]);
		if (context.Env is not null)
			arguments.AddRange(["--env", context.Env]);
		if (paging)
			arguments.Add("--paging");
		return arguments;
	}

	public static string PackageJsonPath(string outDir) => Path.Combine(outDir, "package.json");

	/// <summary>
	/// <c>push</c> bundles the generated files, which import <c>@nullean/journeys</c>, and finds it in the project's
	/// <c>node_modules</c>; without it the bundling fails.
	/// </summary>
	public static string PackageJson() =>
		"{\n"
			+ "  \"private\": true,\n"
			+ "  \"description\": \"Generated by docs-journeys export synthetics. Do not edit.\",\n"
			+ "  \"dependencies\": {\n"
			+ $"    \"{PackageName(JourneysPackage)}\": \"{PackageVersion(JourneysPackage)}\",\n"
			+ $"    \"{PackageName(SyntheticsPackage)}\": \"{PackageVersion(SyntheticsPackage)}\"\n"
			+ "  }\n"
			+ "}\n";

	public static IReadOnlyList<string> InstallArguments { get; } = ["install", "--no-audit", "--no-fund", "--silent"];

	/// <summary>
	/// Run from the output folder, so the generated files find their packages. The API key is not an argument:
	/// <c>@elastic/synthetics</c> reads <see cref="ApiKeyVariable"/> from the environment, so it never appears in a process
	/// list or a log. There is no <c>--tags</c>: for <c>push</c> it filters the monitors to push by their own tags, and the
	/// project (one per environment) is what keeps environments apart.
	/// </summary>
	public static IReadOnlyList<string> PushArguments(string project) =>
		["--yes", SyntheticsPackage, "push", "journeys", "--config", "synthetics.config.ts", "--id", project, "--yes"];

	private static string PackageName(string package) => package[..package.LastIndexOf('@')];

	private static string PackageVersion(string package) => package[(package.LastIndexOf('@') + 1)..];

	/// <summary>The project config <c>push</c> needs: where the project lives, and the defaults every monitor gets.</summary>
	public static string Config(string project, string kibanaUrl, string space, string env, Uri baseUrl)
	{
		Require(Identifier(), project, "project");
		Require(Identifier(), space, "space");
		Require(Identifier(), env, "env");
		if (!Uri.TryCreate(kibanaUrl, UriKind.Absolute, out var kibana) || kibana.Scheme != Uri.UriSchemeHttps)
			throw new ArgumentException($"--kibana-url must be an https URL, not '{kibanaUrl}'.");

		return new StringBuilder()
			.AppendLine("// Generated by docs-journeys export synthetics. Do not edit.")
			.AppendLine("import type { SyntheticsConfig } from '@elastic/synthetics'")
			.AppendLine()
			.AppendLine("export default (): SyntheticsConfig => ({")
			.AppendLine("    params: {")
			.AppendLine($"        url: '{baseUrl.GetLeftPart(UriPartial.Authority)}',")
			.AppendLine($"        environment: '{env}',")
			.AppendLine("    },")
			.AppendLine("    playwrightOptions: {")
			.AppendLine("        ignoreHTTPSErrors: false,")
			.AppendLine("        // Lets the backend exclude our own monitor traffic from tracing and metrics.")
			.AppendLine("        extraHTTPHeaders: {")
			.AppendLine("            'X-Docs-Synthetic-Monitor': 'true',")
			.AppendLine("        },")
			.AppendLine("    },")
			.AppendLine("    monitor: {")
			.AppendLine("        schedule: 15,")
			.AppendLine("        locations: ['germany', 'us_east'],")
			.AppendLine("        privateLocations: [],")
			.AppendLine("    },")
			.AppendLine("    project: {")
			.AppendLine($"        id: '{project}',")
			.AppendLine($"        url: '{JsString(kibana.AbsoluteUri)}',")
			.AppendLine($"        space: '{space}',")
			.AppendLine("    },")
			.AppendLine("})")
			.ToString();
	}

	/// <summary>Escapes a value for the inside of a single-quoted JavaScript string.</summary>
	public static string JsString(string value) =>
		value
			.Replace("\\", "\\\\")
			.Replace("'", "\\'")
			.Replace("\n", "\\n")
			.Replace("\r", "\\r")
			.Replace("\u2028", "\\u2028")
			.Replace("\u2029", "\\u2029");

	/// <summary>The project and environment the generated config names, which <c>push</c> must agree with.</summary>
	public static (string? Project, string? Env) ReadExported(string configPath)
	{
		var text = File.ReadAllText(configPath);
		return (ConfigValue(ProjectId(), text), ConfigValue(Environment(), text));
	}

	private static string? ConfigValue(Regex pattern, string text) => pattern.Match(text) is { Success: true } m ? m.Groups[1].Value : null;

	public static void Require(Regex pattern, string value, string name)
	{
		if (!pattern.IsMatch(value))
			throw new ArgumentException($"--{name} may only contain letters, digits, '-' and '_', not '{value}'.");
	}

	public static void RequireEnv(string value) => Require(Identifier(), value, "env");

	public static void RequireIdentifier(string value, string name) => Require(Identifier(), value, name);

	[GeneratedRegex("^\\s*id: '([^']*)',", RegexOptions.Multiline)]
	private static partial Regex ProjectId();

	[GeneratedRegex("^\\s*environment: '([^']*)',", RegexOptions.Multiline)]
	private static partial Regex Environment();

	[GeneratedRegex("^[A-Za-z0-9][A-Za-z0-9_-]*$")]
	private static partial Regex Identifier();
}
