using System.Text.RegularExpressions;
using Nullean.Cdp.Journeys;
using Nullean.HttpFileParser;

namespace Elastic.Documentation.Journeys.Cli.Synthetics;

internal enum SourceKind
{
	Journey,
	Http
}

/// <summary>A journey or <c>.http</c> file to consider: its name is its path under the export root without the extension.</summary>
internal sealed record ExportSource(string Name, string Text, SourceKind Kind);

/// <summary>A generated Synthetics file; <see cref="FileName"/> is relative to the output folder, such as <c>landing/home.journey.ts</c>.</summary>
internal sealed record ExportedFile(string Name, string FileName, string Content);

internal sealed record ExportSkip(string Name, string Reason);

internal sealed record ExportResult(IReadOnlyList<ExportedFile> Files, IReadOnlyList<ExportSkip> Skipped);

/// <summary>What the exported monitors are for: judged against each source's <c>@requires</c>, and embedded for its <c>feature</c> blocks.</summary>
internal sealed record MonitorContext(IReadOnlySet<string> Features, string? BuildType, string? Env, bool Paging, string? BaseUrl);

/// <summary>Raised for a journey that cannot be exported as written, naming it.</summary>
internal sealed class ExportException(string journey, string message) : Exception($"{journey}: {message}")
{
	public string Journey { get; } = journey;
}

/// <summary>
/// Turns journeys marked <c># @monitor</c> into Elastic Synthetics files. <c>@elastic/synthetics push</c> bundles code and not
/// data files, so each generated file embeds the journey text and runs it with <c>journeySteps</c> (or <c>httpSteps</c>) from
/// <c>@nullean/journeys/synthetics</c>. The output is the same, byte for byte, as <c>journeys export-synthetics</c> of the npm package
/// writes for the same inputs, which a test checks, and depends on nothing but them: no timestamps, a stable order.
/// </summary>
internal static partial class MonitorExporter
{
	/// <summary>The first words of every generated file; a re-export removes only files that start with it.</summary>
	public const string GeneratedMarker = "// Generated by `journeys export-synthetics`";

	/// <summary>The schedules Synthetics accepts, in minutes (ALLOWED_SCHEDULES in <c>@elastic/synthetics</c>).</summary>
	public static readonly IReadOnlyList<int> Schedules = [1, 2, 3, 5, 10, 15, 20, 30, 60, 120, 240];

	/// <summary>The public locations Synthetics accepts.</summary>
	public static readonly IReadOnlyList<string> Locations =
	[
		"japan",
		"india",
		"singapore",
		"australia_east",
		"united_kingdom",
		"germany",
		"canada_east",
		"brazil",
		"us_east",
		"us_west"
	];

	/// <summary>The generated files for the sources that are monitors and apply to the context, and why the others are not.</summary>
	public static ExportResult Export(IEnumerable<ExportSource> sources, MonitorContext context)
	{
		var files = new List<ExportedFile>();
		var skipped = new List<ExportSkip>();
		var ids = new Dictionary<string, string>(StringComparer.Ordinal);
		foreach (var source in sources.OrderBy(s => s.Name, StringComparer.Ordinal))
		{
			var text = source.Text.Replace("\r\n", "\n", StringComparison.Ordinal);
			var info = Describe(source, text, context);
			if (info.Monitor is null)
			{
				skipped.Add(new ExportSkip(source.Name, "no @monitor"));
				continue;
			}
			if (info.Mutates)
			{
				skipped.Add(new ExportSkip(source.Name, "@mutates: a monitor runs against a live site"));
				continue;
			}
			if (info.Unmet is not null)
			{
				skipped.Add(new ExportSkip(source.Name, $"@requires {info.Unmet} does not hold"));
				continue;
			}

			var id = MonitorId(source.Name);
			if (ids.TryGetValue(id, out var other))
				throw new ExportException(source.Name, $"its monitor id '{id}' is already taken by {other}: rename one of them");
			ids[id] = source.Name;
			files.Add(
				new ExportedFile(
					source.Name,
					$"{source.Name}.{(source.Kind == SourceKind.Http ? "http." : "")}journey.ts",
					Render(source, text, info, context)
				)
			);
		}
		return new ExportResult(files, skipped);
	}

	/// <summary>The id a monitor gets: the name with anything but letters, digits, <c>_</c> and <c>-</c> collapsed to <c>-</c>.</summary>
	public static string MonitorId(string name) => NotIdCharacters().Replace(name, "-");

	private sealed record SourceInfo(
		MonitorSettings? Monitor,
		bool Mutates,
		string? Unmet,
		IReadOnlyList<string> Tags,
		IReadOnlyList<string> Alerts
	);

	private sealed record MonitorSettings(int? Schedule, IReadOnlyList<string> Locations);

	// A journey and an .http file say the same things in the same header, through two parsers.
	private static SourceInfo Describe(ExportSource source, string text, MonitorContext context)
	{
		if (source.Kind == SourceKind.Http)
		{
			var metadata = HttpFile.Parse(text, source.Name).Metadata;
			return new SourceInfo(
				metadata.Monitor is { } m ? new MonitorSettings(m.Schedule, m.Locations) : null,
				metadata.Mutates,
				metadata.Unmet(new HttpFileContext(context.Features, context.BuildType, context.Env))?.ToString(),
				metadata.Tags,
				metadata.Alerts
			);
		}

		var journey = Journey.Parse(text, source.Name).Metadata;
		return new SourceInfo(
			journey.Monitor is { } j ? new MonitorSettings(j.Schedule, j.Locations) : null,
			journey.Mutates,
			journey.Unmet(new JourneyContext(context.Features, context.BuildType, context.Env))?.ToString(),
			journey.Tags,
			journey.Alerts
		);
	}

	private static string Render(ExportSource source, string text, SourceInfo info, MonitorContext context)
	{
		var name = source.Name;
		var monitor = info.Monitor!;
		var paging = context.Paging && info.Alerts.Contains("pagerduty", StringComparer.Ordinal);
		var tags = info.Tags.ToList();
		if (paging)
			tags.Add("alert:pagerduty");
		var id = MonitorId(name);

		if (monitor.Schedule is { } schedule && !Schedules.Contains(schedule))
			throw new ExportException(name, $"@monitor schedule={schedule} is not one Synthetics accepts: {string.Join(", ", Schedules)}");
		foreach (var location in monitor.Locations)
		{
			if (!Locations.Contains(location, StringComparer.Ordinal))
				throw new ExportException(
					name,
					$"@monitor location '{location}' is not a public Synthetics location: {string.Join(", ", Locations)}"
				);
		}

		var use = new List<string> { $"id: {Literal(id)}" };
		if (monitor.Schedule is { } s)
			use.Add($"schedule: {s}");
		if (monitor.Locations.Count > 0)
			use.Add($"locations: {Literal(monitor.Locations)}");
		if (tags.Count > 0)
			use.Add($"tags: {Literal(tags)}");
		if (paging)
			use.Add("alert: { status: { enabled: true } }");

		var options = new List<string> { $"baseUrl: {(context.BaseUrl is null ? "params.url" : Literal(context.BaseUrl))}" };
		var features = context.Features.Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToList();
		if (features.Count > 0)
			options.Add($"features: {Literal(features)}");
		if (context.BuildType is not null)
			options.Add($"buildType: {Literal(context.BuildType)}");
		if (context.Env is not null)
			options.Add($"env: {Literal(context.Env)}");
		options.Add("readOnly: true");

		var http = source.Kind == SourceKind.Http;
		var lines = new[]
		{
			$"{GeneratedMarker} from {name}.{(http ? "http" : "journey")}. Do not edit: change the {(http ? "file" : "journey")} and export again.",
			$"import {{ {(http ? "" : "expect, ")}journey, monitor, step }} from '@elastic/synthetics';",
			$"import {{ {(http ? "httpSteps" : "journeySteps")} }} from '@nullean/journeys/synthetics';",
			"",
			$"journey({{ id: {Literal(id)}, name: {Literal(name)} }}, ({{ {(http ? "request" : "page")}, params }}) => {{",
			$"  monitor.use({{ {string.Join(", ", use)} }});",
			http
				? $"  httpSteps({{ request, step, params }}, {Template(text)}, {{ {string.Join(", ", options)} }});"
				: $"  journeySteps({{ page, step, params, expect }}, {Template(text)}, {{ {string.Join(", ", options)} }});",
			"});",
			""
		};
		return string.Join('\n', lines);
	}

	/// <summary>A single-quoted string, or an array of them, as source text.</summary>
	private static string Literal(string value) =>
		$"'{value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("'", "\\'", StringComparison.Ordinal).Replace("\n", "\\n", StringComparison.Ordinal)}'";

	private static string Literal(IEnumerable<string> values) => $"[{string.Join(", ", values.Select(Literal))}]";

	/// <summary>A template literal holding <paramref name="text"/> exactly: backslashes, backticks and <c>${</c> are escaped.</summary>
	private static string Template(string text)
	{
		var body = text
			.Replace("\\", "\\\\", StringComparison.Ordinal)
			.Replace("`", "\\`", StringComparison.Ordinal)
			.Replace("${", "\\${", StringComparison.Ordinal);
		return "`\n" + (body.EndsWith('\n') ? body[..^1] : body) + "\n`";
	}

	/// <summary>The sources in <paramref name="folder"/>: every <c>.journey</c> and <c>.http</c> file, named by its path under it.</summary>
	public static IReadOnlyList<ExportSource> ReadSources(string folder)
	{
		var root = Path.GetFullPath(folder);
		return Directory
			.EnumerateFiles(root, "*", SearchOption.AllDirectories)
			.Where(f => f.EndsWith(".journey", StringComparison.Ordinal) || f.EndsWith(".http", StringComparison.Ordinal))
			.Select(file =>
			{
				var relative = Path.GetRelativePath(root, file).Replace('\\', '/');
				var http = relative.EndsWith(".http", StringComparison.Ordinal);
				var name = relative[..relative.LastIndexOf('.')];
				return new ExportSource(name, File.ReadAllText(file), http ? SourceKind.Http : SourceKind.Journey);
			})
			.OrderBy(s => s.Name, StringComparer.Ordinal)
			.ToList();
	}

	[GeneratedRegex("[^A-Za-z0-9_-]+")]
	private static partial Regex NotIdCharacters();

	/// <summary>Whether <paramref name="content"/> says a previous export generated it, so a re-export may delete it.</summary>
	public static bool IsGenerated(string content) => content.StartsWith(GeneratedMarker, StringComparison.Ordinal);
}
