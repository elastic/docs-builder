using AwesomeAssertions;
using Elastic.Changelog.Rendering;
using Elastic.Documentation.Configuration;
using Elastic.Documentation.Testing;
using Nullean.Snapshots;

namespace Elastic.Changelog.Tests.Changelogs.Render;

public class ChecksumValidationTests() : RenderChangelogTestBase()
{
	// language=yaml
	private const string BundleHeader = """
		products:
		  - product: elasticsearch
		    target: 9.2.0
		""";

	// language=yaml
	private const string ChangelogWithComments =
		"""
		# This is a generated changelog entry
		# Do not edit this file directly
		title: My new feature
		type: feature
		products:
		  - product: elasticsearch
		    target: 9.2.0
		prs:
		- "100"
		""";

	// language=yaml
	private const string ChangelogWithoutComments =
		"""
		title: My new feature
		type: feature
		products:
		  - product: elasticsearch
		    target: 9.2.0
		prs:
		- "100"
		""";

	[Test]
	public async Task RenderChangelogs_ResolvedBundle_RendersWithoutReadingFiles()
	{
		// Arrange — bundles are self-contained: entries carry inline content and the
		// file block is provenance only, so no changelog file exists on disk
		var bundleDir = FileSystem.Path.Join(Paths.WorkingDirectoryRoot.FullName, Guid.NewGuid().ToString());
		FileSystem.Directory.CreateDirectory(bundleDir);

		var bundleFile = FileSystem.Path.Join(bundleDir, "bundle.yaml");
		var bundleContent = CreateResolvedBundleContent(BundleHeader, ("1755268130-feature.yaml", ChangelogWithoutComments));
		await FileSystem.File.WriteAllTextAsync(bundleFile, bundleContent, TestContext.Current!.Execution.CancellationToken);

		var outputDir = FileSystem.Path.Join(Paths.WorkingDirectoryRoot.FullName, Guid.NewGuid().ToString());
		var input = new RenderChangelogsArguments
		{
			Bundles = [new BundleInput { BundleFile = bundleFile }],
			Output = outputDir,
			Title = "9.2.0"
		};

		// Act
		var result = await Service.RenderChangelogs(Collector, input, TestContext.Current!.Execution.CancellationToken);

		// Assert
		result.Should().BeTrue();
		Collector.Errors.Should().Be(0);
		Collector.Warnings.Should().Be(0, "rendering never reads changelog files, so provenance checksums are not verified");

		MockFileSystemDump
			.ToText(FileSystem, outputDir)
			.Should()
			.MatchInlineSnapshot(
				"""
			=== 9.2.0/breaking-changes.md ===
			## 9.2.0 [elastic-9.2.0-breaking-changes]
			_There are no breaking changes associated with this release._
			=== 9.2.0/deprecations.md ===
			## 9.2.0 [elastic-9.2.0-deprecations]
			_There are no deprecations associated with this release._
			=== 9.2.0/index.md ===
			## 9.2.0 [elastic-release-notes-9.2.0]
			### Features and enhancements [elastic-9.2.0-features-enhancements]
			* My new feature. [#100](https://github.com/elastic/elastic/pull/100)
			=== 9.2.0/known-issues.md ===
			## 9.2.0 [elastic-9.2.0-known-issues]
			_There are no known issues associated with this release._
			"""
			);
	}

	[Test]
	public void Checksums_WithAndWithoutComments_AreEqual()
	{
		// Verify that checksums ignore comment lines (normalization strips them)
		var withComments = ComputeSha1(ChangelogWithComments);
		var withoutComments = ComputeSha1(ChangelogWithoutComments);

		withComments.Should().Be(withoutComments, "checksum should be identical regardless of comment lines");
	}
}
